"""Prepare bounded full-text curation batches from a verified pending queue.

Selection never approves labels. Source details stay in a separate manifest;
reviews bind to original candidate hashes, as required by the corpus exporter.
"""
import argparse
from collections import defaultdict
import json
from pathlib import Path
import shutil

from kazstyle.data.corpus import STYLES, digest, file_hash, write_json, write_jsonl
from kazstyle.data.export_corpus import read_recipe, verify_integrity


def prepare(corpus, recipe_path, out, *, style='colloquial', per_stratum=32,
            min_words=8, max_words=55, seed=202610183, prior_reviews=()):
    corpus, recipe_path, out = Path(corpus), Path(recipe_path), Path(out)
    if out.exists():
        raise FileExistsError('Choose a new curation packet directory')
    if style not in STYLES or any(type(n) is not int for n in [per_stratum,min_words,max_words]):
        raise ValueError('Invalid style or integer selection limits')
    if not 1 <= min_words <= max_words or per_stratum < 1:
        raise ValueError('Invalid word range or stratum limit')
    manifest = verify_integrity(corpus)
    if not {'audit.jsonl','recipe.json'}.issubset(manifest):
        raise ValueError('Corpus lacks checksummed queue/recipe provenance')
    if file_hash(recipe_path) != file_hash(corpus/'recipe.json'):
        raise ValueError('Curation recipe differs from the completed corpus')
    recipe, rows, _ = read_recipe(recipe_path)
    by_id = {row['doc_id']:row for row in rows}
    reviewed, review_hashes = set(), {}
    for path in map(Path,prior_reviews):
        review = json.loads(path.read_text(encoding='utf-8'))
        if review.get('reviewer_kind') != 'assistant':
            raise ValueError('Curation history must identify the assistant reviewer')
        review_hashes[str(path)] = file_hash(path)
        for decision in review['decisions']:
            row = by_id.get(decision['doc_id'])
            if row is None or digest(row['text']) != decision.get('text_sha256'):
                raise ValueError('Stale curation history')
            reviewed.add(row['doc_id'])
    audit = {row['doc_id']:row for row in map(json.loads,
             (corpus/'audit.jsonl').read_text(encoding='utf-8').splitlines())}
    strata = defaultdict(list)
    for row in rows:
        status = audit.get(row['doc_id'])
        if (not status or status['disposition'] != 'review' or row['style'] != style
                or row.get('assistant_review') or row['doc_id'] in reviewed):
            continue
        # Contact, language, extraction and other safety/quality flags need their
        # own investigation. Do not silently clear them with a semantic review.
        if set(status['review_flags'])-{'source_genre_requires_semantic_review'}:
            continue
        if not min_words <= len(row['text'].split()) <= max_words:
            continue
        strata[(row.get('genre') or 'unknown', row.get('source_domain') or 'unknown',
                row.get('upstream_domain') or '')].append(row)
    selected, eligible = [], {}
    for key, values in sorted(strata.items()):
        values.sort(key=lambda r:digest(f'{seed}|select|'+r['doc_id']))
        selected.extend(values[:per_stratum])
        eligible['|'.join(key)] = len(values)
    selected.sort(key=lambda r:digest(f'{seed}|show|'+r['doc_id']))
    if not selected:
        raise ValueError('No unreviewed full texts satisfy the declared limits')
    shown = [{'n':i,'doc_id':r['doc_id'],'text':r['text'],
              'text_sha256':digest(r['text']),'words':len(r['text'].split())}
             for i,r in enumerate(selected,1)]
    out.mkdir(parents=True)
    write_jsonl(out/'packet.jsonl',shown)
    shutil.copy2(Path(__file__),out/'sampler.py')
    write_json(out/'manifest.json',{
        'purpose':'ai_assisted_curation_not_a_final_test',
        'corpus':str(corpus),'corpus_complete_sha256':file_hash(corpus/'COMPLETE.json'),
        'recipe':str(recipe_path),'recipe_sha256':file_hash(recipe_path),
        'input_hashes':{item['path']:item['sha256'] for item in recipe['inputs']},
        'prior_review_hashes':review_hashes,'style_sampling_stratum':style,
        'per_stratum':per_stratum,'min_words':min_words,'max_words':max_words,'seed':seed,
        'eligible_by_stratum':eligible,'documents':len(shown),
        'packet_sha256':file_hash(out/'packet.jsonl'),'sampler_sha256':file_hash(out/'sampler.py'),
        'review_extent':'Entire original candidate text; no truncation or paraphrase',
        'limitations':['Targeted queue curation, not a population accuracy estimate.',
                       'No models queried and no decisions generated by the sampler.',
                       'Review precedes final export cleanup; transformed text needs its own checks.',
                       'Assistant decisions are not independent human expert labels.'],
        'sources':{r['doc_id']:{k:r.get(k) for k in ['genre','source_domain',
                   'upstream_domain','source_url','parent_id','author_group','source_sha256']}
                   for r in selected}})
    return {'packet':str(out/'packet.jsonl'),'documents':len(shown),
            'words':sum(r['words'] for r in shown),'labels_approved':0}


if __name__ == '__main__':
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--corpus',type=Path,required=True)
    parser.add_argument('--recipe',type=Path,required=True)
    parser.add_argument('--out-dir',type=Path,required=True)
    parser.add_argument('--style',choices=STYLES,default='colloquial')
    parser.add_argument('--per-stratum',type=int,default=32)
    parser.add_argument('--min-words',type=int,default=8)
    parser.add_argument('--max-words',type=int,default=55)
    parser.add_argument('--seed',type=int,default=202610183)
    parser.add_argument('--prior-review',type=Path,action='append',default=[])
    args=parser.parse_args()
    print(json.dumps(prepare(args.corpus,args.recipe,args.out_dir,style=args.style,
          per_stratum=args.per_stratum,min_words=args.min_words,max_words=args.max_words,
          seed=args.seed,prior_reviews=args.prior_review)))
